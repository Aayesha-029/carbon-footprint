export const LanguageProvider = ({ children }) => {
  const [language, setLanguage] = useState('en');
  const [loading, setLoading] = useState(true);
  const [translationsData, setTranslationsData] = useState(translations.en);

  const loadLanguage = useCallback(async () => {
    try {
      setLoading(true);
      const savedLang = localStorage.getItem('preferredLanguage');
      if (savedLang && translations[savedLang]) {
        setLanguage(savedLang);
        setTranslationsData(translations[savedLang]);
      } else {
        setLanguage('en');
        setTranslationsData(translations.en);
        localStorage.setItem('preferredLanguage', 'en');
      }
    } catch (err) {
      console.error('Error loading language:', err);
      setLanguage('en');
      setTranslationsData(translations.en);
    } finally {
      setLoading(false);
    }
  }, []);

  const changeLanguage = useCallback((langCode) => {
    if (translations[langCode]) {
      console.log('🌍 Changing language to:', langCode);
      setLanguage(langCode);
      setTranslationsData(translations[langCode]);
      localStorage.setItem('preferredLanguage', langCode);
      
      window.dispatchEvent(new CustomEvent('languageChanged', { 
        detail: { language: langCode, translations: translations[langCode] }
      }));
      
      // Force reload to apply translations to all components
      setTimeout(() => {
        window.location.reload();
      }, 300);
    }
  }, []);

  // ============================================================
  // FIXED: t() function - Properly handles nested keys
  // ============================================================
  const t = useCallback((key, ...args) => {
    if (!key) return key;
    
    const keys = key.split('.');
    let value = translationsData;
    
    for (const k of keys) {
      if (value && value[k] !== undefined && value[k] !== null) {
        value = value[k];
      } else {
        // Fallback to English
        let fallback = translations.en;
        for (const fk of keys) {
          if (fallback && fallback[fk] !== undefined && fallback[fk] !== null) {
            fallback = fallback[fk];
          } else {
            // If even English doesn't have it, return the key itself
            return key;
          }
        }
        value = fallback;
        break;
      }
    }
    
    // If the final value is an object, try to convert it to string
    if (typeof value === 'object' && value !== null) {
      // If it's an object with a default value, try to get it
      if (value.default) {
        value = value.default;
      } else {
        // Try to stringify or return the key
        return key;
      }
    }
    
    if (typeof value === 'string' && args && args.length > 0) {
      args.forEach((arg, index) => {
        value = value.replace(new RegExp(`\\{${index}\\}`, 'g'), arg);
      });
    }
    
    return typeof value === 'string' ? value : key;
  }, [translationsData]);

  useEffect(() => {
    loadLanguage();
  }, [loadLanguage]);

  const value = {
    language,
    loading,
    t,
    changeLanguage,
    translationsData,
    availableLanguages: Object.keys(translations),
  };

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
};

export default LanguageContext;